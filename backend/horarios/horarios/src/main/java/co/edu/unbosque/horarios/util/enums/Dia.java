package co.edu.unbosque.horarios.util.enums;

/**
 * Enum que representa los días de la semana disponibles para la programación
 * de horarios.
 *
 * @author Prisma Web
 */
public enum Dia {

    /** Representa el día lunes. */
    LUNES,

    /** Representa el día martes. */
    MARTES,

    /** Representa el día miércoles. */
    MIERCOLES,

    /** Representa el día jueves. */
    JUEVES,

    /** Representa el día viernes. */
    VIERNES,

    /** Representa el día sábado. */
    SABADO

}
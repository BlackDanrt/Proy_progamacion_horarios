package co.edu.unbosque.horarios.util.enums;

/**
 * Enum que representa las categorías del escalafón docente de la Universidad El
 * Bosque (Estatuto Docente, artículo 10).
 *
 * @author Prisma Web
 */
public enum Escalafon {
	PROFESOR_AUXILIAR_I,
	
	PROFESOR_AUXILIAR_II,

	/** Representa la categoría de instructor asistente. */
	INSTRUCTOR_ASISTENTE,

	/** Representa la categoría de instructor asociado. */
	INSTRUCTOR_ASOCIADO,

	/** Representa la categoría de profesor asistente. */
	PROFESOR_ASISTENTE,

	/** Representa la categoría de profesor asociado. */
	PROFESOR_ASOCIADO,

	/** Representa la categoría de profesor titular. */
	PROFESOR_TITULAR

}
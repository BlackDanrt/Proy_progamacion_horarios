package co.edu.unbosque.horarios.util.enums;

/**
 * Enum que representa las especialidades disponibles para los profesores
 * del sistema de gestión de horarios.
 *
 * @author Prisma Web
 */
public enum Especialidad {

    /** Representa la especialidad en bases de datos. */
    BASES_DE_DATOS,

    /** Representa la especialidad en desarrollo de software. */
    DESARROLLO_SOFTWARE,

    /** Representa la especialidad en ciberseguridad. */
    CIBERSEGURIDAD,

    /** Representa la especialidad en lógica matemática. */
    LOGICA_MATEMATICA,

    /** Representa la especialidad en inteligencia artificial. */
    INTELIGENCIA_ARTIFICIAL,

    /** Representa la especialidad en redes y comunicaciones. */
    REDES_Y_COMUNICACIONES,

    /** Representa la especialidad en estructuras de datos y algoritmos. */
    ESTRUCTURAS_DATOS_Y_ALGORITMOS,

    /** Representa la especialidad en sistemas operativos. */
    SISTEMAS_OPERATIVOS,

    /** Representa la especialidad en arquitectura de software. */
    ARQUITECTURA_DE_SOFTWARE,

    /** Representa la especialidad en ingeniería de requisitos. */
    INGENIERIA_DE_REQUISITOS

}